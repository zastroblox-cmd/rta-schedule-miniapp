-- RTA Schedule API: initial schema.
-- Run this in the database SQL editor before starting the API.
-- Do not commit real credentials or disable RLS in production.

create table if not exists public.schedule_groups (
    id bigint generated by default as identity primary key,
    code text not null unique,
    display_name text not null,
    faculty text not null default 'Юридический факультет',
    course smallint not null default 2,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.schedule_lessons (
    id bigint generated by default as identity primary key,
    group_id bigint not null references public.schedule_groups(id) on delete cascade,
    week_code char(1) not null check (week_code in ('A', 'B')),
    weekday smallint not null check (weekday between 0 and 6), -- Monday=0
    start_time time not null,
    end_time time not null,
    subject text not null,
    lesson_type text not null default '',
    room text not null default '',
    teacher text not null default '',
    sort_order integer not null default 0,
    source_note text not null default '',
    created_at timestamptz not null default now(),
    constraint lesson_time_order check (end_time > start_time)
);

create index if not exists idx_schedule_lessons_lookup
    on public.schedule_lessons(group_id, week_code, weekday, start_time);

-- Date-specific exceptions. "remove" identifies an existing weekly lesson
-- by start_time + subject; "add" provides the fields for an extra lesson.
create table if not exists public.schedule_date_overrides (
    id bigint generated by default as identity primary key,
    group_id bigint not null references public.schedule_groups(id) on delete cascade,
    lesson_date date not null,
    action text not null check (action in ('add', 'remove')),
    match_start_time time,
    match_subject text,
    start_time time,
    end_time time,
    subject text,
    lesson_type text not null default '',
    room text not null default '',
    teacher text not null default '',
    note text not null default '',
    created_at timestamptz not null default now(),
    constraint override_remove_match check (
        action <> 'remove' or (match_start_time is not null and match_subject is not null)
    ),
    constraint override_add_fields check (
        action <> 'add' or (
            start_time is not null and end_time is not null and
            subject is not null and end_time > start_time
        )
    )
);

create index if not exists idx_schedule_overrides_lookup
    on public.schedule_date_overrides(group_id, lesson_date);

-- Telegram users are created/updated only by the trusted API after initData validation.
create table if not exists public.telegram_users (
    telegram_id bigint primary key,
    username text,
    first_name text not null default '',
    last_name text not null default '',
    selected_group_id bigint references public.schedule_groups(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.group_representatives (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null references public.telegram_users(telegram_id) on delete cascade,
    group_id bigint not null references public.schedule_groups(id) on delete cascade,
    is_active boolean not null default true,
    granted_at timestamptz not null default now(),
    unique(telegram_id, group_id)
);

create table if not exists public.subscriptions (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null references public.telegram_users(telegram_id) on delete cascade,
    plan_code text not null check (plan_code in ('month', 'six_months', 'year')),
    status text not null check (status in ('pending', 'active', 'expired', 'cancelled', 'refunded')),
    starts_at timestamptz,
    expires_at timestamptz,
    payment_provider text not null default '',
    provider_payment_id text unique,
    created_at timestamptz not null default now()
);

create index if not exists idx_subscriptions_user_status
    on public.subscriptions(telegram_id, status, expires_at);

create table if not exists public.schedule_change_log (
    id bigint generated by default as identity primary key,
    group_id bigint not null references public.schedule_groups(id) on delete cascade,
    lesson_date date not null,
    actor_telegram_id bigint references public.telegram_users(telegram_id) on delete set null,
    action text not null,
    before_data jsonb,
    after_data jsonb,
    created_at timestamptz not null default now()
);

