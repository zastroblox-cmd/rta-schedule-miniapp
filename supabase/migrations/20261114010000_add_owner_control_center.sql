create table if not exists public.app_subscriptions (
  telegram_user_id text primary key check (telegram_user_id ~ '^[0-9]{1,24}$'),
  plan_code text not null check (plan_code in ('month_50','half_year_300','year_600','manual')),
  status text not null default 'active' check (status in ('active','expired','cancelled')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  note text,
  updated_at timestamptz not null default now(),
  updated_by text
);
create index if not exists app_subscriptions_status_expiry_idx on public.app_subscriptions(status, expires_at);
create table if not exists public.app_feature_flags (
  flag_key text primary key check (flag_key ~ '^[a-z][a-z0-9_]{1,63}$'),
  enabled boolean not null default false,
  message text,
  updated_at timestamptz not null default now(),
  updated_by text
);
insert into public.app_feature_flags(flag_key, enabled, message) values
 ('maintenance_mode', false, 'Проводятся технические работы. Попробуйте позже.'),
 ('reminders_enabled', true, null), ('announcements_enabled', true, null), ('subscriptions_enabled', false, null)
on conflict (flag_key) do nothing;
create table if not exists public.app_broadcast_log (
  id bigint generated by default as identity primary key, message text not null, audience text not null,
  recipient_count integer not null default 0, sent_count integer not null default 0, failed_count integer not null default 0,
  status text not null check (status in ('sent','partial','failed')), created_at timestamptz not null default now(), created_by text
);
create table if not exists public.app_payment_ledger (
  id bigint generated by default as identity primary key,
  telegram_user_id text check (telegram_user_id is null or telegram_user_id ~ '^[0-9]{1,24}$'),
  amount_rub integer not null check (amount_rub > 0),
  plan_code text not null check (plan_code in ('month_50','half_year_300','year_600','manual')),
  status text not null default 'confirmed' check (status in ('pending','confirmed','refunded','failed')),
  provider text not null default 'manual', external_payment_id text, paid_at timestamptz,
  created_at timestamptz not null default now(), note text
);
create index if not exists app_payment_ledger_status_paid_idx on public.app_payment_ledger(status, paid_at);
alter table public.app_subscriptions enable row level security;
