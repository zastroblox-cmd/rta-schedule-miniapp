create or replace function public.get_app_user_list(p_secret text, p_limit integer default 200, p_offset integer default 0)
returns jsonb language plpgsql security definer set search_path to 'pg_catalog', 'analytics_private'
as $function$
declare result jsonb;
begin
 if p_secret is null or p_secret is distinct from (select config_value from analytics_private.config where config_key='analytics_secret') then
  raise exception 'not authorized' using errcode='42501';
 end if;
 select coalesce(jsonb_agg(jsonb_build_object('telegram_user_id',telegram_user_id,'first_seen_at',first_seen_at,'last_seen_at',last_seen_at) order by last_seen_at desc),'[]'::jsonb)
 into result from (select telegram_user_id,first_seen_at,last_seen_at from analytics_private.app_users order by last_seen_at desc limit greatest(1,least(coalesce(p_limit,200),500)) offset greatest(0,coalesce(p_offset,0))) users;
 return result;
end;
$function$;
revoke all on function public.get_app_user_list(text,integer,integer) from public, anon, authenticated;
grant execute on function public.get_app_user_list(text,integer,integer) to service_role;
